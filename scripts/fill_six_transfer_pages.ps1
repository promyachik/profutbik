function Set-FrontMatterValue {
    param(
        [string]$FrontMatter,
        [string]$Key,
        [string]$YamlValue
    )

    $Pattern = "(?m)^" + [regex]::Escape($Key) + "\s*:\s*.*$"
    $Line = $Key + ": " + $YamlValue

    if ([regex]::IsMatch($FrontMatter, $Pattern)) {
        return [regex]::Replace($FrontMatter, $Pattern, $Line, 1)
    }

    return $FrontMatter.TrimEnd() + "`r`n" + $Line
}

function Quote-Yaml {
    param([string]$Value)
    return '"' + ($Value.Replace("\", "\\").Replace('"', '\"')) + '"'
}

